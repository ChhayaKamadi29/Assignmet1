#Program to find quotient and remainder of two numbers.

# take input
num1 = int(input('Enter the number:'))
num2 = int(input('Enter the number:'))

#calculate Quotient
Quo = num1//num2

#calculate remainder
Rem = num1%num2

#display quotient
print(f'Quotient of two number is {Quo}')
print(f'Remainder of two number is {Rem}')

